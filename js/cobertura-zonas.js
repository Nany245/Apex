// ---- Dibuja el mapa cuando todo esté listo ----
function initMapaCobertura() {
  var el = document.getElementById("map");
  if (!el || typeof L === "undefined" || el._leaflet_id) return;

  var map = L.map("map", { scrollWheelZoom: true });

  L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
    maxZoom: 18,
    attribution: "&copy; OpenStreetMap"
  }).addTo(map);

  var grupo = L.featureGroup().addTo(map);

  COBERTURA_ZONAS.forEach(function (z) {
    var poly = L.polygon(z.poligono, {
      color: z.color,
      weight: 2,
      fillColor: z.color,
      fillOpacity: 0.30
    }).addTo(grupo).bindTooltip(z.nombre, { sticky: true, direction: "top", className: "cb-zona-tip" });

    poly.on("mouseover", function () { this.setStyle({ fillOpacity: 0.5, weight: 3 }); });
    poly.on("mouseout",  function () { this.setStyle({ fillOpacity: 0.30, weight: 2 }); });
  });

  map.fitBounds(grupo.getBounds().pad(0.05));
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initMapaCobertura);
} else {
  initMapaCobertura();
}
